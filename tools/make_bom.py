#!/usr/bin/env python3
"""
Build bom.md + tayda_bom.csv for one module, in the Free Modular BOM style.

KiCad symbol fields (Symbol Fields Table in the schematic editor):
  Board     Front / Back / Both            (optional, for stacked builds)
  Part      Resistor, Capacitor, Jack...    (optional; guessed from ref if blank)
  Tayda     Tayda SKU, e.g. A-2203          (blank = not at Tayda, gets 🔴)
  Source    other suppliers, e.g. "DigiKey" or "Thonk"  (optional)
  Comment   build notes                     (optional)

Export (KiCad 8+), from the OTLABS folder:
  kicad-cli sch export bom "Soul Ring TVCA/kicad/soul_ring.kicad_sch" \
    --fields 'Reference,Value,${QUANTITY},Board,Part,Tayda,Source,Comment' \
    --group-by 'Value,Board,Part,Tayda,Source,Comment' \
    -o "Soul Ring TVCA/bom.csv"

Run:
  python3 tools/make_bom.py "Soul Ring TVCA" --cart <Tayda saved-cart URL>
Without --cart, an existing cart link in bom.md is kept.
"""
import argparse, csv, re, sys
from pathlib import Path

PREFIX = {"R": "Resistor", "RV": "Potentiometer", "C": "Capacitor", "D": "Diode",
          "Q": "Transistor", "U": "IC", "J": "Jack", "SW": "Switch", "LED": "LED",
          "L": "Inductor", "FB": "Ferrite bead", "TP": "Test point"}
ORDER = ["Front", "Back", "Both", ""]
CART_RE = re.compile(r"<!-- cart: (\S+) -->")

def col(row, *names):
    low = {(k or "").strip().lower(): (v or "").strip() for k, v in row.items()}
    for n in names:
        if n.lower() in low:
            return low[n.lower()]
    return ""

def guess_part(ref):
    p = re.match(r"[A-Za-z]+", ref.split(",")[0].strip())
    p = p.group(0).upper() if p else ""
    return PREFIX.get(p, PREFIX.get(p[:1], ""))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("module_dir")
    ap.add_argument("--csv", default="bom.csv")
    ap.add_argument("--cart")
    a = ap.parse_args()
    mod = Path(a.module_dir)
    src = mod / a.csv
    if not src.exists():
        sys.exit(f"missing {src}: export it from KiCad first (see top of this script)")

    rows = []
    with open(src, newline="", encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            ref = col(r, "Reference", "Refs")
            if not ref or ref.startswith("#"):
                continue
            qty = col(r, "${QUANTITY}", "Quantity", "Qty") or len(re.split(r"[ ,]+", ref))
            rows.append(dict(ref=ref, qty=int(float(qty)), value=col(r, "Value"),
                             board=col(r, "Board"), part=col(r, "Part") or guess_part(ref),
                             tayda=col(r, "Tayda"), source=col(r, "Source"),
                             comment=col(r, "Comment")))

    # Tayda quick-order CSV
    tq = {}
    for r in rows:
        if r["tayda"]:
            tq[r["tayda"]] = tq.get(r["tayda"], 0) + r["qty"]
    with open(mod / "tayda_bom.csv", "w", newline="") as f:
        w = csv.writer(f); w.writerow(["sku", "qty"]); w.writerows(tq.items())

    bom_md = mod / "bom.md"
    cart = a.cart
    if not cart and bom_md.exists():
        m = CART_RE.search(bom_md.read_text()); cart = m.group(1) if m else None

    def source(r):
        s = []
        if r["tayda"]:
            s.append(f"[Tayda](https://www.taydaelectronics.com/catalogsearch/result/?q={r['tayda']})")
        if r["source"]:
            s.append(r["source"])
        return " and ".join(s) or "?"

    rows.sort(key=lambda r: (ORDER.index(r["board"]) if r["board"] in ORDER else 9, r["part"], r["ref"]))
    L = ["## Components", "",
         "<!-- generated by tools/make_bom.py from the KiCad fields; edit those, not this file -->"]
    if cart:
        L.append(f"<!-- cart: {cart} -->")
    L += ["", "(Most) parts on Tayda: " + (f"[cart link]({cart})" if cart else "cart link TBD")
          + ", [quick-order CSV](tayda_bom.csv)", "",
          ]
    multi = any(r["board"] for r in rows)
    hdr = ["", "Board", "Reference", "Qty", "Part", "Value", "Source", "Comment"]
    if not multi:
        hdr.remove("Board")
    L += ["| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
    for r in rows:
        flag = "🔴" if not r["tayda"] else ""
        cells = [flag, r["board"], r["ref"], str(r["qty"]), r["part"], r["value"], source(r), r["comment"]]
        if not multi:
            cells.pop(1)
        L.append("| " + " | ".join(cells) + " |")
    L += ["", "🔴 = Missing from Tayda BOM", ""]
    bom_md.write_text("\n".join(L))
    print(f"wrote {bom_md} and tayda_bom.csv: {len(rows)} lines, "
          f"{sum(1 for r in rows if not r['tayda'])} not at Tayda")

if __name__ == "__main__":
    main()
